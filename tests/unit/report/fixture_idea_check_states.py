# Post fields `utils/validation/evidence_breadth.py` reads. Anything else on a post is
# dead weight in a 1.5-3 MB stage_2 capture.
_POST_FIELDS = ("post_id", "author", "subreddit", "platform", "created_utc")
# Pain fields the block reads.
_PAIN_FIELDS = (
    "title", "severity_score", "mention_count", "representative_quotes", "source_post_ids",
)
_METADATA_FIELDS = (
    "user_idea_text", "user_idea_brief", "user_idea_inferred_fields", "user_idea_pivot",
    "user_idea_identity_terms", "niche_incumbent_map", "idea_ruled_out",
)
_NICHE_FIELDS = ("niche_description", "resolved_primary_audience", "user_target_audience")

_CACHE: dict[str, dict] = {}


def state_path(slug: str) -> Path:
    return STATES_DIR / f"{slug}.state.json"


def golden_path(slug: str) -> Path:
    return STATES_DIR / f"{slug}.block.generated.json"


def load_state_fixture(slug: str) -> dict:
    if slug not in _CACHE:
        _CACHE[slug] = json.loads(state_path(slug).read_text())
    return deepcopy(_CACHE[slug])


def state_from_fixture(fx: dict) -> SimpleNamespace:
    """The same state shape `fixture_056b2c68.state_from_fixture` builds, so both
    fixture families feed `build_idea_validation_block` through one contract."""
    m = fx["metadata"]
    return SimpleNamespace(
        user_idea_text=m["user_idea_text"],
        user_idea_brief=m["user_idea_brief"],
        user_idea_inferred_fields=m["user_idea_inferred_fields"],
        user_idea_pivot=m["user_idea_pivot"],
        user_idea_identity_terms=m["user_idea_identity_terms"],
        # NOT persisted on any captured checkpoint: `user_idea_brief_parity` is stamped
        # by the Q1 probe onto live state and never reached `metadata.json`. None is the
        # value every restored run carries, so it is the honest one here.
        user_idea_brief_parity=None,
        idea_generation=SimpleNamespace(
            solution_ideas=[SimpleNamespace(**i) for i in fx["ideas"]]),
        pain_point_analysis=SimpleNamespace(
            pain_points=[SimpleNamespace(**p) for p in fx["pains"]]),
        social_content=SimpleNamespace(
            reddit_posts=[SimpleNamespace(**p) for p in fx["posts_reddit"]],
            generic_posts=[SimpleNamespace(**p) for p in fx["posts_generic"]]),
        niche_context=SimpleNamespace(**fx["niche_context"]),
        niche_incumbent_map=m["niche_incumbent_map"],
        idea_ruled_out=m["idea_ruled_out"],
    )


def state_for(slug: str) -> SimpleNamespace:
    return state_from_fixture(load_state_fixture(slug))


def generate_block(slug: str) -> dict:
    """The producer call that IS each golden's provenance."""
    from nicheiq.report.idea_validation_block import build_idea_validation_block

    block = build_idea_validation_block(state_for(slug), "validate_idea")
    assert block is not None and block["outcome"] != "not_evaluated", slug
    return json.loads(json.dumps(block))


# ── capture (needs output/checkpoints/) ────────────────────────────────────────────

def _select(row: dict, fields) -> dict:
    """Present keys only — a post row carries `subreddit` OR `platform`, never both,
    and inventing the missing one would be authoring."""
    return {k: row[k] for k in fields if k in row}


def _select_all(row: dict, fields) -> dict:
    """Every key, absent ones as None — `metadata.json` omits a field it never wrote
    (`idea_ruled_out` on a run that ruled nothing out), and the restored state reads
    that as None either way."""
    return {k: row.get(k) for k in fields}


def capture(slug: str, checkpoint_root: Path) -> dict:
    folder, why = CAPTURES[slug]
    src = checkpoint_root / folder
    meta = json.loads((src / "metadata.json").read_text())
    niche = json.loads((src / "stage_1_niche_context.json").read_text())
    pains = json.loads((src / "stage_3_pain_points.json").read_text())
    ideas = json.loads((src / "stage_5_3_refinement.json").read_text())
    social = json.loads((src / "stage_2_social_content.json").read_text())

    pain_rows = pains["pain_points"] if isinstance(pains, dict) else pains
    return {
        "_provenance": {
            "checkpoint": folder,
            "job_id": folder.rsplit("_", 3)[-3],
            "entry_mode": meta.get("entry_mode"),
            "why": why,
            "trim": (
                "ideas: stage_5_3_refinement.json::solution_ideas VERBATIM (whole rows). "
                "pains: " + ", ".join(_PAIN_FIELDS) + ". "
                "posts: " + ", ".join(_POST_FIELDS) + " — the fields "
                "utils/validation/evidence_breadth.py reads. "
                "metadata/niche_context: copied key-for-key."
            ),
            "recapture": "python -m tests.unit.report.fixture_idea_check_states",
        },
        "metadata": _select_all(meta, _METADATA_FIELDS),
        "niche_context": _select_all(niche, _NICHE_FIELDS),
        "ideas": ideas["solution_ideas"],
        "pains": [_select(p, _PAIN_FIELDS) for p in pain_rows],
        "posts_reddit": [_select(p, _POST_FIELDS) for p in (social.get("reddit_posts") or [])],
        "posts_generic": [_select(p, _POST_FIELDS) for p in (social.get("generic_posts") or [])],
    }


def main() -> None:  # pragma: no cover — provenance script, not a test
    root = Path(__file__).resolve().parents[3] / "output" / "checkpoints"
    STATES_DIR.mkdir(parents=True, exist_ok=True)
    for slug in CAPTURES:
        payload = capture(slug, root)
        state_path(slug).write_text(json.dumps(payload, indent=1) + "\n")
        print(f"captured {slug}: {state_path(slug)}")


if __name__ == "__main__":  # pragma: no cover
    main()
