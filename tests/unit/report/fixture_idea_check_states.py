"""Captured `validate_idea` run states — one per BRANCH TUPLE through the
idea_validation block, and the loader that rebuilds them.

WHY THIS EXISTS. `fixture_056b2c68` is one captured run in two states (graded and
refused), and its drift checks are byte-exact — which is the right machinery, pointed at
too little. That run carries `incumbent_parity: "none found"`, `red_team_verdict: None`,
no typed findings, `unanchored_hypothesis: False`, `candidate_status: "active"`, an empty
`idea_ruled_out`, a `not_attempted` pivot and one anchored pain in the `limited` band. A
mutation campaign over `report/idea_validation_block.py` returned 476 survivors, and a
triage found that essentially all of the real ones are *the branches that run does not
take*: the `occupied` family (`shipped by` / `partial by` parity), the `ruled_out` family
(a demoted seed), the typed-red-team-findings path in `_kill_risks`, `_demotion_reason`,
`_display_embedded`, the pivot record, and `named_buyer_count` as an actual number rather
than `None`.

THE REMEDY IS MORE CAPTURED STATES, NOT STRONGER ASSERTIONS. Each state below is a real
run off `output/checkpoints/`, selected because its seed carries a branch tuple no other
committed fixture reaches. Each has a vendored golden block generated by calling the real
`build_idea_validation_block`, held byte-exact by `test_idea_validation_fixture.py`.

DERIVED, NEVER AUTHORED — the doctrine `test_not_evaluated_fixture_contract.py` states and
this module inherits. Nothing here is typed by hand:

  * `ideas` are the run's `stage_5_3_refinement.json::solution_ideas` VERBATIM, whole. Not
    field-selected: the 056b2c68 trim dropped `audience_fit` and `idea_ruled_out`, and the
    two consumers that read them (`_alternatives.named_buyer_count`, `_demotion_reason`)
    have been unmeasurable ever since. A trim that silently answers "None" for a field the
    producer stamps is the same class of lie as a hand-written shape.
  * `pains` keep the five fields `_anchored_pains`/`_related_pains`/`_market_signal_risk`/
    `compute_evidence_breadth` read, verbatim.
  * `posts` keep the four fields `evidence_breadth` reads (`post_id`, `author`,
    `subreddit`/`platform`, `created_utc`) — the same slice `fixture_056b2c68` keeps, and
    the reason the whole 1.5-3 MB `stage_2_social_content.json` does not have to ship.
  * `metadata` / `niche_context` are copied key-for-key off the checkpoint.

Recapture (needs `output/checkpoints/`, which is gitignored — so this is a provenance
record first and a runnable script second):

    python -m tests.unit.report.fixture_idea_check_states

Regenerate the goldens after any deliberate change to the block:

    IDEA_VALIDATION_FIXTURE_REGEN=1 pytest tests/unit/report/test_idea_validation_fixture.py
"""

