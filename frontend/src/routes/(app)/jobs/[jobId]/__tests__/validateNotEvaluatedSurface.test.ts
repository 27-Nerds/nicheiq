/**
 * A `validate_idea` run can end `outcome: 'not_evaluated'` — the pipeline refused to grade
 * the user's idea, for one of six typed causes, ALL of which are ours. The job page is the
 * surface that told the user otherwise for four rounds: every sentence that branched on "is
 * this a validate run" or "is there an idea_validation block" asserted a grading that never
 * happened, because the block is emitted on a refusal too.
 *
 * Round 4 fixed nine of those sentences and shipped them with no render test — "no harness
 * exists for this route", which was false: the four files beside this one already render
 * `+page.svelte`. A critic copied that scaffold, reproduced the refused page in one attempt,
 * and found a TENTH surface in one extra click: the guided tour, whose "Show me around
 * again" control still sat on the refused page and replayed "run it again in your own
 * words" — the exact sentence the verdict card had been fixed to stop saying.
 *
 * So this file drives the page rather than reading it. It runs the real `+page.server.ts`
 * load against a realistic refused `/solutions` response, renders the real page component,
 * and asserts on rendered DOM — including the DOM that only exists after a click, because
 * the workbench header mounts behind a disclosure and a header assertion made without
 * expanding it passes against unfixed code.
 */
