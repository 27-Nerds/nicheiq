async function loadPageData(
  solutionsBody: unknown,
  status = "AWAITING_SELECTION",
  previewReport: unknown = null,
) {
  mocks.fetchBackend.mockImplementation((path: string) => {
    if (path === "/api/jobs/job-1") return Promise.resolve(response(backendJob(status)));
    if (path === "/api/jobs/job-1/solutions") return Promise.resolve(response(solutionsBody));
    // A terminal stop takes the artifact path instead of the selection snapshot.
    if (path === "/api/jobs/job-1/preview-report" && previewReport) {
      return Promise.resolve(response(previewReport));
    }
    return Promise.resolve(response({}, 404));
  });
  const data = await load(event()) as Record<string, unknown>;
  return {
    ...data,
    creditBalance: 100,
    stageCosts: {
      discovery: 5, deep_research: 15, landing_page: 5, regenerate_ideas: 2, seed_idea: 3,
    },
  } as Record<string, unknown>;
}

/** Renders the page for a refused (or graded) run and waits for the verdict to land. */
async function renderRun(ideaValidation: unknown, status = "AWAITING_SELECTION") {
  const data = await loadPageData(
    verifiedSolutionsResponse(ideaValidation, status === "AWAITING_SELECTION"
      ? {}
      : { status }),
    status,
    { niche: "vet clinics", generated_at: "2026-08-01T00:00:00.000Z",
      idea_validation: ideaValidation },
  );
  const view = render(PageComponent, { props: { data: data as never } });
  return { data, view };
}

