/**
 * The in-run progress screen. It reads no report data at all — it takes `entryMode` and
 * nothing else — so no sweep keyed on consumers of `idea_validation` could reach it, and
 * every idea-check sentence on it was written for a run that WAS graded. The route into
 * it is the refusal sentence on /selection/review ("…so there is no version of it to
 * research. Deep Research will cover X"): the user clicks through that and lands here.
 */
describe("job page — the in-run progress screen on a refused run", () => {
  type View = { container: HTMLElement };
  const progress = (view: View) =>
    view.container.querySelector(".research-progress") as HTMLElement | null;
  const segments = (view: View) =>
    Array.from(view.container.querySelectorAll(".rp-seg")).map((seg) => ({
      label: squash(seg.querySelector(".rp-seg-label")?.textContent),
      state: seg.getAttribute("data-state"),
    }));

  it("shows no completed verdict step, and promises no spec, while Deep Research runs",
    async () => {
      const { view } = await renderRun(NOT_EVALUATED_IV, "RUNNING_PHASE2");
      await waitFor(() => expect(progress(view)).toBeTruthy());
      const text = squash(progress(view)!.textContent);

      // The track marked phase 2 DONE on a run that refused to produce a verdict. It is
      // dropped rather than relabelled: every segment before the active one fills, so a
      // kept segment would be a bar that can never complete.
      expect(segments(view)).toEqual([
        { label: "Research", state: "done" },
        { label: "Deep Research", state: "active" },
      ]);
      expect(text).not.toContain("Your verdict");

      // Present tense, on work that had already stopped.
      expect(text).not.toContain("Checking your idea against this market");
      expect(text).toContain("This run couldn't grade your idea");

      // The spec-and-score promise: neither was written, and neither will be.
      expect(text).not.toContain("write your pitch up as a complete product spec");
      expect(text).toContain(
        "Your pitch was not written up as a product spec or scored on this run.");

      // Chrome, not the failure story. The six typed causes have exactly one home
      // (SEED_FAILURE_COPY); a second copy here is what this ledger exists to prevent.
      expect(text).not.toContain(NOT_EVALUATED_IV.headline);
      expect(text).not.toContain(NOT_EVALUATED_IV.failure_next_step);
    });

  it("leaves a GRADED run's progress chrome exactly as it was", async () => {
    const { view } = await renderRun(GRADED_IV, "RUNNING_PHASE2");
    await waitFor(() => expect(progress(view)).toBeTruthy());
    const text = squash(progress(view)!.textContent);

    expect(segments(view)).toEqual([
      { label: "Research", state: "done" },
      { label: "Your verdict", state: "done" },
      { label: "Deep Research", state: "active" },
    ]);
    expect(text).toContain("Checking your idea against this market");
    expect(text).toContain(
      "write your pitch up as a complete product spec — name included — and score it");
    expect(text).not.toContain("couldn't grade your idea");
  });

  /**
   * THE PROPERTY, not the two states that break it. The screen used to take a BOOLEAN whose
   * `false` meant "graded", so any caller that could not READ the outcome asserted one.
   *
   * Two ways to get there, both reproduced below and both previously silent — no retry, no
   * failure marker, none of the "Idea check snapshot unavailable … Refresh check" treatment
   * the same page gives an untrusted artifact at AWAITING_SELECTION:
   *
   *   QUEUED + DEEP_RESEARCH — `GET /preview-report` 400'd for the entire queue wait, which
   *     is unbounded under load, on the screen that says "You can safely close this tab".
   *     And this is the DESIGNED destination of /selection/review's "we could not grade your
   *     idea" handoff, so the refused run is the one most likely to be standing here.
   *   RUNNING_PHASE2 + 5xx — the artifact exists and is allowed; the fetch just failed.
   *
   * The screen now takes a three-state outcome defaulting to "unknown", and states neither
   * result there: the caption drops to provenance, the method sentence is withheld, and the
   * middle segment is named for the work that certainly happened rather than for a verdict
   * that may or may not exist.
   */
  const loadWithPreviewStatus = async (
    status: string,
    previewStatus: number,
    body: unknown,
    activeDispatchKind: string | null = "DEEP_RESEARCH",
  ) => {
    mocks.fetchBackend.mockImplementation((path: string) => {
      if (path === "/api/jobs/job-1") {
        return Promise.resolve(response({ ...backendJob(status), activeDispatchKind }));
      }
      if (path === "/api/jobs/job-1/preview-report") {
        return Promise.resolve(response(body, previewStatus));
      }
      if (path === "/api/jobs/job-1/solutions") {
        return Promise.resolve(response(verifiedSolutionsResponse(null, { status })));
      }
      return Promise.resolve(response({}, 404));
    });
    const data = await load(event()) as Record<string, unknown>;
    return render(PageComponent, { props: { data: { ...data, creditBalance: 100 } as never } });
  };

  const REFUSED_PREVIEW = {
    niche: "vet clinics",
    generated_at: "2026-08-01T00:00:00.000Z",
    idea_validation: NOT_EVALUATED_IV,
  };

  it("reads the refusal through the QUEUED window before Deep Research starts", async () => {
    const view = await loadWithPreviewStatus("QUEUED", 200, REFUSED_PREVIEW);
    await waitFor(() => expect(progress(view)).toBeTruthy());
    const text = squash(progress(view)!.textContent);

    // The backend half (`isQueuedDeepResearch`, routes/jobs.ts) and this fetch are one fix:
    // without the loader change the response is never requested, without the backend change
    // it is a 400. Either alone leaves the assertions below red.
    expect(segments(view).map((s) => s.label)).toEqual(["Research", "Deep Research"]);
    expect(text).toContain("This run couldn't grade your idea");
    expect(text).not.toContain("Checking your idea against this market");
    expect(text).not.toContain("write your pitch up as a complete product spec");
  });

  it("asserts NO outcome when the artifact cannot be read (5xx)", async () => {
    const view = await loadWithPreviewStatus("RUNNING_PHASE2", 503, {});
    await waitFor(() => expect(progress(view)).toBeTruthy());
    const text = squash(progress(view)!.textContent);

    // Neither claim. The old boolean printed the graded one here.
    expect(text).not.toContain("Checking your idea against this market");
    expect(text).not.toContain("write your pitch up as a complete product spec");
    expect(text).not.toContain("This run couldn't grade your idea");
    expect(text).not.toContain("Your pitch was not written up as a product spec");
    expect(text).toContain("Started from your idea");

    // The middle segment: neither dropped (that asserts no verdict) nor "Your verdict"
    // filled and done (that asserts one).
    expect(segments(view)).toEqual([
      { label: "Research", state: "done" },
      { label: "Idea check", state: "done" },
      { label: "Deep Research", state: "active" },
    ]);
  });

  it("still promises the spec during Phase 1, where 'unknown' means 'not yet'", async () => {
    // The control for the safe default: "unknown" is the state of every discovery-phase run,
    // and withholding the method sentence there would delete it from the happy path.
    const view = await loadWithPreviewStatus("RUNNING", 404, {}, "DISCOVERY");
    await waitFor(() => expect(progress(view)).toBeTruthy());
    const text = squash(progress(view)!.textContent);

    expect(text).toContain("Checking your idea against this market");
    expect(text).toContain(
      "write your pitch up as a complete product spec — name included — and score it");
    expect(text).not.toContain("Started from your idea");
  });
});

